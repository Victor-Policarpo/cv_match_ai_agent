from enum import StrEnum

from pydantic import BaseModel, Field, model_validator


class RequirementStatus(StrEnum):
    FOUND = "found"
    PARTIAL = "partial"
    NOT_FOUND = "not_found"


class RequirementEvidence(BaseModel):
    requirement: str = Field(min_length=1)
    status: RequirementStatus
    evidence: str = ""

    @model_validator(mode="after")
    def evidence_for_matches(self) -> "RequirementEvidence":
        if self.status != RequirementStatus.NOT_FOUND and not self.evidence.strip():
            raise ValueError("Requisitos encontrados ou parciais precisam de evidência")
        return self


class AnalysisRequest(BaseModel):
    resume_id: str
    job_description: str = Field(min_length=30, max_length=20000)


class AnalysisResponse(BaseModel):
    compatibility_score: int = Field(ge=0, le=100)
    summary: str
    strengths: list[str]
    missing_requirements: list[str]
    requirements_analysis: list[RequirementEvidence]
    recommendations: list[str]
    score_method: str


class AnalysisDraft(BaseModel):
    """Fields generated by the LLM; scoring and explanation are server-owned."""

    summary: str
    requirements_analysis: list[RequirementEvidence]
    recommendations: list[str]
